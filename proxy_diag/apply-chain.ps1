[System.IO.File]::WriteAllText($rt, $runtimeYaml, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "[ok] runtime config written"

# --- 4) config.yaml mode ---
$c = [System.IO.File]::ReadAllText($cfg, [System.Text.Encoding]::UTF8)
$c = [regex]::Replace($c, '(?m)^mode:\s*\S+', 'mode: rule')
[System.IO.File]::WriteAllText($cfg, $c, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "[ok] config.yaml mode -> rule"

# --- 5) validate ---
& $core -t -f $rt -d $base *> $null
if ($LASTEXITCODE -ne 0) { throw 'mihomo config test FAILED' }
Write-Host '[ok] mihomo -t passed'

# --- 6) restart ---
Get-Process verge-mihomo, clash-verge -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
Start-Sleep -Seconds 3
Start-Process $exe
for ($i = 0; $i -lt 40; $i++) {
    Start-Sleep -Milliseconds 1500
    if (Get-NetTCPConnection -LocalPort 7897 -State Listen -ErrorAction SilentlyContinue) { break }
}
Start-Sleep -Seconds 3

# --- 7) system proxy -> Clash ---
$k = 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Internet Settings'
Set-ItemProperty $k -Name ProxyServer -Value '127.0.0.1:7897'
Set-ItemProperty $k -Name ProxyEnable  -Value 1
$sig = '[DllImport("wininet.dll",SetLastError=true)]public static extern bool InternetSetOption(IntPtr h,int o,IntPtr b,int l);'
$w = Add-Type -MemberDefinition $sig -Name W3 -Namespace N3 -PassThru
[void]$w::InternetSetOption([IntPtr]::Zero, 39, [IntPtr]::Zero, 0)
[void]$w::InternetSetOption([IntPtr]::Zero, 37, [IntPtr]::Zero, 0)

# --- 8) verify ---
$ip = (& curl.exe -sS -m 40 -x socks5h://127.0.0.1:7897 https://ipinfo.io/ip 2>&1) -join ''
Write-Host ''
Write-Host ("exit IP via Clash 7897 -> " + $ip.Trim())
if ($ip.Trim() -eq '72.245.197.103') {
    Write-Host '[PASS] chain is working' -ForegroundColor Green
} else {
    Write-Host '[FAIL] exit IP is not the static IP - check StarSky 加速状态' -ForegroundColor Red
}
