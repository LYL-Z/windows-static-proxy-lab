# =====================================================================
#  APPLY: 应用"静态IP + StarSky首跳"链式代理配置 (幂等, 可重复执行)
#  拓扑: 应用 -> Clash(7897) -> StarSky(127.0.0.1:11119) -> 72.245.197.103:9506 -> 互联网
#  前置: StarSky 必须处于"加速中"(本地 11119 端口在监听)
#  凭据: 运行时从现有 profile 读取, 不落盘明文到本脚本
# =====================================================================
$ErrorActionPreference = 'Stop'

$base = 'C:\Users\Lenovo\AppData\Roaming\io.github.clash-verge-rev.clash-verge-rev'
$prof = Join-Path $base 'profiles\LWMoQxn0PeIP.yaml'
$rt   = Join-Path $base 'clash-verge.yaml'
$cfg  = Join-Path $base 'config.yaml'
$core = 'C:\Program Files\Clash Verge\verge-mihomo.exe'
$exe  = 'C:\Program Files\Clash Verge\clash-verge.exe'
$pipe = '\\.\pipe\verge-mihomo-sidecar-release-582392de1c279b7f7ab1f8c38277da07a8b55c8486ecf17cc5c285d158fec75f'

# --- 0) 前置检查: StarSky 首跳是否在监听 ---
$hop = $null
try { $hop = (Get-NetTCPConnection -LocalPort 11119 -State Listen -ErrorAction SilentlyContinue).OwningProcess } catch {}
if (-not $hop) {
    Write-Host '!! 127.0.0.1:11119 没有监听 -> 请先打开 StarSky 并点击"开始加速"' -ForegroundColor Yellow
    throw 'first hop (StarSky 11119) not listening'
}
Write-Host ("[ok] first hop 127.0.0.1:11119 listening (pid " + $hop + ")")

# --- 1) 读取凭据 ---
$raw = [System.IO.File]::ReadAllText($prof, [System.Text.Encoding]::UTF8)
$u = $null; $p = $null
if ($raw -match 'username:\s*"([^"]+)"') { $u = $Matches[1] }
if ($raw -match 'password:\s*"([^"]+)"') { $p = $Matches[1] }
if (-not $u -or -not $p) {
    $bakProf = 'D:\claude防封\proxy_diag\backup\20261118-011610\profiles\LWMoQxn0PeIP.yaml'
    $raw = [System.IO.File]::ReadAllText($bakProf, [System.Text.Encoding]::UTF8)
    if ($raw -match 'username:\s*"([^"]+)"') { $u = $Matches[1] }
    if ($raw -match 'password:\s*"([^"]+)"') { $p = $Matches[1] }
}
if (-not $u -or -not $p) { throw 'credentials not found' }
Write-Host ("[ok] credentials loaded (user_len=" + $u.Length + " pass_len=" + $p.Length + ")")

# --- 2) profile ---
$profileYaml = @"
# NexIP 美国华盛顿 原生静态IP -> Clash Verge Rev / Mihomo (链式)
mixed-port: 7897
allow-lan: false
mode: rule
log-level: info
ipv6: false
unified-delay: true

proxies:
  - name: "STAR-首跳"
    type: http
    server: 127.0.0.1
    port: 11119
  - name: "美国-华盛顿-SOCKS5"
    type: socks5
    server: 72.245.197.103
    port: 9506
    username: "$u"
    password: "$p"
    udp: false
    dialer-proxy: "STAR-首跳"

proxy-groups:
  - name: "PROXY"
    type: select
    proxies:
      - "美国-华盛顿-SOCKS5"
      - "DIRECT"

rules:
  - MATCH,PROXY
"@
[System.IO.File]::WriteAllText($prof, $profileYaml, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "[ok] profile written"

# --- 3) runtime ---
$runtimeYaml = @"
